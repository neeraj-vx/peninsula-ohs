-- Cleanup procedure for the demo seed — called from the seed script.
-- Uses session_replication_role to bypass FK chains.
CREATE OR REPLACE FUNCTION cleanup_demo_org(p_org_name text DEFAULT 'Peninsula Demo Pty Ltd')
RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE v_org uuid;
BEGIN
  SELECT id INTO v_org FROM organisations WHERE name = p_org_name;
  IF v_org IS NULL THEN RETURN; END IF;

  SET LOCAL session_replication_role = replica;

  DELETE FROM kpi_snapshots                WHERE organisation_id = v_org;
  DELETE FROM workforce_hours_logs         WHERE organisation_id = v_org;
  DELETE FROM speak_up_reports             WHERE organisation_id = v_org;
  DELETE FROM toolbox_talk_attendees       WHERE delivery_id IN (SELECT id FROM toolbox_talk_deliveries WHERE organisation_id = v_org);
  DELETE FROM toolbox_talk_deliveries      WHERE organisation_id = v_org;
  DELETE FROM toolbox_talk_templates       WHERE organisation_id = v_org;
  DELETE FROM env_monitoring_records       WHERE organisation_id = v_org;
  DELETE FROM env_monitoring_stations      WHERE organisation_id = v_org;
  DELETE FROM emergency_activations        WHERE organisation_id = v_org;
  DELETE FROM emergency_drills             WHERE organisation_id = v_org;
  DELETE FROM emergency_wardens            WHERE organisation_id = v_org;
  DELETE FROM muster_points                WHERE organisation_id = v_org;
  DELETE FROM emergency_response_plans     WHERE organisation_id = v_org;
  DELETE FROM contractor_site_access_log   WHERE organisation_id = v_org;
  DELETE FROM contractor_workers           WHERE organisation_id = v_org;
  DELETE FROM contractor_companies         WHERE organisation_id = v_org;
  DELETE FROM ppe_issuances                WHERE organisation_id = v_org;
  DELETE FROM ppe_items                    WHERE organisation_id = v_org;
  DELETE FROM health_check_records         WHERE organisation_id = v_org;
  DELETE FROM worker_health_profiles       WHERE organisation_id = v_org;
  DELETE FROM action_assignments           WHERE organisation_id = v_org;
  DELETE FROM action_extensions            WHERE organisation_id = v_org;
  DELETE FROM action_evidence              WHERE organisation_id = v_org;
  DELETE FROM action_comments              WHERE organisation_id = v_org;
  DELETE FROM actions                      WHERE organisation_id = v_org;
  DELETE FROM hazard_reports               WHERE organisation_id = v_org;
  DELETE FROM rca_fishbone_causes          WHERE organisation_id = v_org;
  DELETE FROM rca_fishbone                 WHERE organisation_id = v_org;
  DELETE FROM rca_five_whys                WHERE organisation_id = v_org;
  DELETE FROM investigations               WHERE organisation_id = v_org;
  DELETE FROM incident_capa                WHERE organisation_id = v_org;
  DELETE FROM incident_status_history      WHERE organisation_id = v_org;
  DELETE FROM incident_medical             WHERE organisation_id = v_org;
  DELETE FROM incident_witnesses           WHERE organisation_id = v_org;
  DELETE FROM incident_evidence            WHERE organisation_id = v_org;
  DELETE FROM incident_people_involved     WHERE organisation_id = v_org;
  DELETE FROM incidents                    WHERE organisation_id = v_org;
  DELETE FROM audit_finding_actions        WHERE organisation_id = v_org;
  DELETE FROM audit_evidence               WHERE organisation_id = v_org;
  DELETE FROM audit_findings               WHERE organisation_id = v_org;
  DELETE FROM audit_criteria               WHERE organisation_id = v_org;
  DELETE FROM audit_sections               WHERE organisation_id = v_org;
  DELETE FROM audits                       WHERE organisation_id = v_org;
  DELETE FROM inspection_actions           WHERE organisation_id = v_org;
  DELETE FROM inspection_response_evidence WHERE organisation_id = v_org;
  DELETE FROM inspection_responses         WHERE organisation_id = v_org;
  DELETE FROM inspections                  WHERE organisation_id = v_org;
  DELETE FROM inspection_schedules         WHERE organisation_id = v_org;
  DELETE FROM inspection_template_questions WHERE template_id IN (SELECT id FROM inspection_templates WHERE organisation_id = v_org);
  DELETE FROM inspection_template_sections  WHERE template_id IN (SELECT id FROM inspection_templates WHERE organisation_id = v_org);
  DELETE FROM inspection_templates         WHERE organisation_id = v_org;
  DELETE FROM permit_document_links        WHERE organisation_id = v_org;
  DELETE FROM permit_asset_links           WHERE organisation_id = v_org;
  DELETE FROM permit_isolation_certs       WHERE organisation_id = v_org;
  DELETE FROM permit_conditions            WHERE organisation_id = v_org;
  DELETE FROM permit_approvals             WHERE organisation_id = v_org;
  DELETE FROM permit_ppe_requirements      WHERE organisation_id = v_org;
  DELETE FROM permit_control_measures      WHERE organisation_id = v_org;
  DELETE FROM permit_hazards               WHERE organisation_id = v_org;
  DELETE FROM permit_workers               WHERE organisation_id = v_org;
  DELETE FROM permits                      WHERE organisation_id = v_org;
  DELETE FROM risk_linked_incidents        WHERE organisation_id = v_org;
  DELETE FROM risk_reviews                 WHERE organisation_id = v_org;
  DELETE FROM risk_controls                WHERE organisation_id = v_org;
  DELETE FROM risks                        WHERE organisation_id = v_org;
  DELETE FROM jsa_step_hazards             WHERE step_id IN (SELECT s.id FROM jsa_steps s JOIN jsas j ON s.jsa_id = j.id WHERE j.organisation_id = v_org);
  DELETE FROM jsa_steps                    WHERE jsa_id IN (SELECT id FROM jsas WHERE organisation_id = v_org);
  DELETE FROM jsas                         WHERE organisation_id = v_org;
  DELETE FROM loto_isolation_points        WHERE procedure_id IN (SELECT id FROM loto_procedures WHERE organisation_id = v_org);
  DELETE FROM loto_procedures              WHERE organisation_id = v_org;
  DELETE FROM chemicals                    WHERE organisation_id = v_org;
  DELETE FROM asset_incident_links         WHERE organisation_id = v_org;
  DELETE FROM asset_documents              WHERE organisation_id = v_org;
  DELETE FROM asset_maintenance_parts      WHERE organisation_id = v_org;
  DELETE FROM asset_maintenance_records    WHERE organisation_id = v_org;
  DELETE FROM asset_out_of_service_events  WHERE organisation_id = v_org;
  DELETE FROM assets                       WHERE organisation_id = v_org;
  DELETE FROM training_records             WHERE organisation_id = v_org;
  DELETE FROM training_courses             WHERE organisation_id = v_org;
  DELETE FROM document_links               WHERE organisation_id = v_org;
  DELETE FROM document_acknowledgements    WHERE organisation_id = v_org;
  DELETE FROM document_version_reviews     WHERE organisation_id = v_org;
  DELETE FROM document_versions            WHERE document_id IN (SELECT id FROM documents WHERE organisation_id = v_org);
  DELETE FROM documents                    WHERE organisation_id = v_org;
  DELETE FROM compliance_tasks             WHERE organisation_id = v_org;
  DELETE FROM compliance_obligations       WHERE organisation_id = v_org;
  DELETE FROM hires                        WHERE organisation_id = v_org;
  DELETE FROM reference_counters           WHERE organisation_id = v_org;
  DELETE FROM work_areas                   WHERE organisation_id = v_org;
  DELETE FROM teams                        WHERE organisation_id = v_org;
  DELETE FROM departments                  WHERE organisation_id = v_org;
  DELETE FROM sites                        WHERE organisation_id = v_org;
  DELETE FROM user_site_assignments        WHERE organisation_id = v_org;
  DELETE FROM user_team_memberships        WHERE organisation_id = v_org;
  DELETE FROM user_roles                   WHERE organisation_id = v_org;
  DELETE FROM user_profiles                WHERE organisation_id = v_org;
  DELETE FROM organisations                WHERE id = v_org;
END;
$$;

GRANT EXECUTE ON FUNCTION cleanup_demo_org(text) TO service_role;
